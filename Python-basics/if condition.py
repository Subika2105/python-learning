#if condition
a=10
b=20
if a>b:
    print("a is greater")
else:
    print("b is greater")
#nested if condition
a=10
b=10
if a>b:
    print("a is greater")
elif a==b:
    print("a and b are equal")
else:
    print("b is greater")
