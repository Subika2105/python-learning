#membership operator
fruits=["apple","banana","cherry"]
print("apple" in fruits)
print("grape" in fruits)
print("grape" not in fruits)

#identity operator
a = [1,2]
b = a
print(a is not b)

#bitwise operators
x=2
y=2
print(x&y)#and
print(x|y)#or
