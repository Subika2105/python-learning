#arithmetic operators
x = 15
y = 4
print(x + y)
print(x - y)
print(x * y)
print(x / y)
print(x % y)
print(x ** y)
print(x // y)
#comparison operators
a=10
b=10
print(a==b)
print(a!=b)
print(a>b)
print(a<b)
print(a>=b)
print(a<=b)
#another example
age=18
if age<18:
    print("eligible to play")
else:
    print("not eligible to play")
#logical operators
a=10
b=10
print(a==10 and b==10)
#or operator
fruit="apple"
if fruit=="apple" or fruit=="banana":
    print("fruit is apple or banana")
#not operator
a=10
print(not a==10)
#another example
